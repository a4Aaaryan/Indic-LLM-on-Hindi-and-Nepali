def check_template(sp, text):
    text = text.replace('{E1}', 'राम').replace('{E2}', 'श्याम').replace('{E3}', 'हरि').replace('{E4}', 'सिता').replace('{E5}', 'गीता')
    text = text.replace('{V1}', '50').replace('{Item1}', 'किताब')
    ids = sp.encode(text)
    unks = [sp.id_to_piece(i) for i in ids if sp.is_unknown(i)]
    return unks

